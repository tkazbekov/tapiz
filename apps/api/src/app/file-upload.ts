import { FastifyInstance, FastifyReply, FastifyRequest } from 'fastify';
import db from './db/index.js';
import path from 'path';
import { randomUUID } from 'node:crypto';
import FastifyMultipart, {
  MultipartFile,
  MultipartValue,
} from '@fastify/multipart';
import { createAuthContext } from './app.context.js';
import fastifyStatics from '@fastify/static';
import { unlink, mkdirSync } from 'fs';
import sharp from 'sharp';
import { z } from 'zod';

interface CheckAccessSuccess {
  success: true;
}

interface CheckAccessError {
  success: false;
  code: number;
  error: string;
}

type CheckAccessResult = CheckAccessSuccess | CheckAccessError;

const uploadFolder =
  process.env['UPLOADS_DIR'] || path.resolve(process.cwd(), 'uploads');

mkdirSync(uploadFolder, { recursive: true });

// only names generated by the upload handler (uuid + .webp)
const uploadFileNamePattern = /^[0-9a-f-]{36}\.webp$/;

async function checkAccess(
  boardId: string,
  req: FastifyRequest,
  res: FastifyReply,
): Promise<CheckAccessResult> {
  const context = await createAuthContext({ req, res });

  if (!context.user) {
    return { success: false, code: 401, error: 'Unauthorized' };
  }

  const board = await db.board.getBoard(boardId);

  if (!board) {
    return { success: false, code: 404, error: 'Board not found' };
  }

  const haveAccess = await db.board.haveAccess(boardId, context.user.sub);

  if (!haveAccess) {
    return { success: false, code: 401, error: 'Unauthorized' };
  }

  return { success: true };
}

export async function fileUpload(fastify: FastifyInstance) {
  fastify.register(FastifyMultipart, {
    attachFieldsToBody: true,
    limits: {
      fieldSize: 1000000, // Max field value (in bytes)
      fileSize: 5000000, // For multipart forms, the max file size
    },
  });
  // serve: false keeps reply.sendFile without exposing an unguarded route
  fastify.register(fastifyStatics, {
    root: uploadFolder,
    serve: false,
  });

  fastify.route<{
    // fields are client controlled and may be missing
    Body:
      | {
          boardId?: MultipartValue<string>;
          file?: MultipartFile;
        }
      | undefined;
  }>({
    config: {
      rateLimit: {
        max: 30,
        timeWindow: '1 minute',
      },
    },
    method: 'POST',
    url: '/api/upload-file-board',
    handler: async (req, res) => {
      const boardId = z.uuid().safeParse(req.body?.boardId?.value);
      const file = req.body?.file;

      if (!boardId.success || typeof file?.toBuffer !== 'function') {
        res.code(400);
        return { error: 'Invalid upload' };
      }

      const access = await checkAccess(boardId.data, req, res);
      if (!access.success) {
        res.code(access.code);
        return { error: access.error };
      }

      const data = await file.toBuffer();

      if (!data) {
        res.code(400);
        return { error: 'Error uploading file' };
      }

      const fileName = randomUUID() + '.webp';

      await sharp(data, {
        animated: true,
      }).toFile(path.join(uploadFolder, fileName));

      await db.board.addFileToBoard(boardId.data, fileName);

      return {
        url: fileName,
      };
    },
  });

  fastify.route<{
    Params: {
      filename: string;
    };
  }>({
    method: 'GET',
    url: '/api/uploads/:filename',
    handler: async (req, res) => {
      if (!uploadFileNamePattern.test(req.params.filename)) {
        res.code(404);
        return { error: 'File not found' };
      }

      const file = await db.board.getFile(req.params.filename);

      if (!file) {
        res.code(404);
        return { error: 'File not found' };
      }

      const access = await checkAccess(file.boardId, req, res);

      if (!access.success) {
        res.code(404);
        return { error: 'File not found' };
      }

      res.header('X-Content-Type-Options', 'nosniff');

      return res.sendFile(file.name);
    },
  });
}

export async function deleteBoardFiles(boardId: string) {
  const files = await db.board.getBoardFiles(boardId);

  for (const file of files) {
    unlink(path.join(uploadFolder, file.name), (err) => {
      if (err) {
        console.error(err);
      }
    });
  }
}
