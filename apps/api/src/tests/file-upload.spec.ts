import { randomUUID } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { FastifyInstance } from 'fastify';
import sharp from 'sharp';
import { startDB } from '../app/db/init-db';
import {
  buildAuthTestApp,
  createGuest,
  createMultipleUsers,
  getUserCaller,
} from './test-helpers';

const uploadsDir = process.env['UPLOADS_DIR'] ?? '';

function multipart(
  fields: Record<string, string>,
  file?: Buffer,
  cookie = 'tapiz_session=1',
) {
  const boundary = '----tapiz-test';
  const parts = Object.entries(fields).map(
    ([name, value]) =>
      `--${boundary}\r\nContent-Disposition: form-data; name="${name}"\r\n\r\n${value}\r\n`,
  );
  const chunks: Buffer[] = parts.map((part) => Buffer.from(part));

  if (file) {
    chunks.push(
      Buffer.from(
        `--${boundary}\r\nContent-Disposition: form-data; name="file"; filename="image.png"\r\nContent-Type: image/png\r\n\r\n`,
      ),
      file,
      Buffer.from('\r\n'),
    );
  }

  chunks.push(Buffer.from(`--${boundary}--\r\n`));

  return {
    payload: Buffer.concat(chunks),
    headers: {
      'content-type': `multipart/form-data; boundary=${boundary}`,
      origin: process.env['FRONTEND_URL'],
      cookie,
    },
  };
}

describe('file upload', () => {
  let app: FastifyInstance;
  let boardId: string;
  let image: Buffer;

  beforeAll(async () => {
    await startDB();
    await createMultipleUsers();

    await createGuest(0);

    app = await buildAuthTestApp();

    boardId = (await (await getUserCaller(1)).board.create({ name: 'files' }))
      .id;

    image = await sharp({
      create: {
        width: 2,
        height: 2,
        channels: 3,
        background: '#ff0000',
      },
    })
      .png()
      .toBuffer();
  });

  afterAll(async () => {
    await app.close();
  });

  it('does not expose the uploads folder as a static route', async () => {
    const fileName = `${randomUUID()}.webp`;
    writeFileSync(path.join(uploadsDir, fileName), 'not guarded');

    const response = await app.inject({
      method: 'GET',
      url: `/uploads/${fileName}`,
    });

    expect(response.statusCode).toEqual(404);
    expect(response.body).not.toContain('not guarded');
  });

  it('rejects file names that were not generated by the upload', async () => {
    for (const name of ['..%2F..%2Fetc%2Fpasswd', 'file.png', 'a.webp']) {
      const response = await app.inject({
        method: 'GET',
        url: `/api/uploads/${name}`,
        headers: { cookie: 'tapiz_session=1' },
      });

      expect(response.statusCode).toEqual(404);
    }
  });

  it('rejects uploads without a valid board id', async () => {
    const missing = await app.inject({
      method: 'POST',
      url: '/api/upload-file-board',
      ...multipart({}, image),
    });

    expect(missing.statusCode).toEqual(400);

    const invalid = await app.inject({
      method: 'POST',
      url: '/api/upload-file-board',
      ...multipart({ boardId: 'not-a-uuid' }, image),
    });

    expect(invalid.statusCode).toEqual(400);

    const json = await app.inject({
      method: 'POST',
      url: '/api/upload-file-board',
      headers: {
        cookie: 'tapiz_session=1',
        origin: process.env['FRONTEND_URL'],
      },
      payload: {},
    });

    expect(json.statusCode).toEqual(400);
  });

  it('rejects uploads to boards without access', async () => {
    const response = await app.inject({
      method: 'POST',
      url: '/api/upload-file-board',
      ...multipart({ boardId }, image, 'tapiz_session=2'),
    });

    expect(response.statusCode).toEqual(401);
  });

  it('stores uploads in UPLOADS_DIR and serves them to board members', async () => {
    const upload = await app.inject({
      method: 'POST',
      url: '/api/upload-file-board',
      ...multipart({ boardId }, image),
    });

    expect(upload.statusCode).toEqual(200);

    const { url } = upload.json<{ url: string }>();

    expect(existsSync(path.join(uploadsDir, url))).toEqual(true);

    const download = await app.inject({
      method: 'GET',
      url: `/api/uploads/${url}`,
      headers: { cookie: 'tapiz_session=1' },
    });

    expect(download.statusCode).toEqual(200);
    expect(download.headers['x-content-type-options']).toEqual('nosniff');

    const outsider = await app.inject({
      method: 'GET',
      url: `/api/uploads/${url}`,
      headers: { cookie: 'tapiz_session=2' },
    });

    expect(outsider.statusCode).toEqual(404);
  });

  it('lets guests view images on public boards but not upload', async () => {
    const owner = await getUserCaller(1);
    const publicBoard = await owner.board.create({ name: 'public files' });
    await owner.board.changePrivacy({
      boardId: publicBoard.id,
      isPublic: true,
    });

    const upload = await app.inject({
      method: 'POST',
      url: '/api/upload-file-board',
      ...multipart({ boardId: publicBoard.id }, image),
    });
    const { url } = upload.json<{ url: string }>();

    const guestUpload = await app.inject({
      method: 'POST',
      url: '/api/upload-file-board',
      ...multipart({ boardId: publicBoard.id }, image, 'tapiz_session=g0'),
    });

    expect(guestUpload.statusCode).toEqual(403);
    expect(guestUpload.json()).toEqual({ error: 'ACCOUNT_REQUIRED' });

    const guestDownload = await app.inject({
      method: 'GET',
      url: `/api/uploads/${url}`,
      headers: { cookie: 'tapiz_session=g0' },
    });

    expect(guestDownload.statusCode).toEqual(200);
  });
});
